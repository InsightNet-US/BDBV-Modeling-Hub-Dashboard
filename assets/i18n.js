const _i18nWarned = new Set();
function _i18nRaw(key) {
  const d = I18N[LANG] || I18N.en;
  if (key in d) return d[key];
  if (key in I18N.en) return I18N.en[key];
  if (!_i18nWarned.has(key)) { _i18nWarned.add(key); console.warn('i18n: missing key', key); }
  return null;
}
function _i18nFill(s, vars) {
  return vars ? String(s).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : String(s);
}
/** translated string for key, with {placeholders} filled from vars */
function t(key, vars) {
  const raw = _i18nRaw(key);
  if (raw == null) return key;
  if (Array.isArray(raw)) return raw;
  return _i18nFill(typeof raw === 'object' ? raw.other : raw, vars);
}
/** one/other form chosen by n (French: singular for 0 and 1); n is also available as {n} */
function tn(key, n, vars) {
  const raw = _i18nRaw(key);
  if (raw == null) return key;
  const one = LANG === 'fr' ? Math.abs(n) <= 1 : n === 1;
  const form = typeof raw === 'object' && !Array.isArray(raw) ? (one ? raw.one : raw.other) : raw;
  return _i18nFill(form, Object.assign({ n }, vars || {}));
}
/** fill the static text of index.html from data-i18n* attributes; nodes with unknown keys are left alone */
function applyStatic() {
  const set = (attr, fn) => document.querySelectorAll(`[${attr}]`).forEach(el => {
    const key = el.getAttribute(attr);
    if (key in I18N.en) fn(el, t(key)); else if (!_i18nWarned.has(key)) { _i18nWarned.add(key); console.warn('i18n: unknown static key', key); }
  });
  set('data-i18n', (el, s) => { el.textContent = s; });
  set('data-i18n-title', (el, s) => { el.title = s; });
  set('data-i18n-ph', (el, s) => { el.placeholder = s; });
  set('data-i18n-aria', (el, s) => { el.setAttribute('aria-label', s); });
  document.documentElement.lang = LANG;
  document.title = t('page.title');
  const md = document.querySelector('meta[name="description"]'); if (md) md.content = t('page.desc');
}
